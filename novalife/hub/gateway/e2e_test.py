#!/usr/bin/env python3
"""End-to-end test of the reference gateway: mark -> submit -> verify.

Starts the gateway on a free port, marks a phantom with the Python reference,
submits it, verifies it (the gateway extracts the tag from the image and
checks the handle), and also verifies an unmarked image (must fail).

Run: .venv/bin/python novalife_hub/gateway/e2e_test.py
"""
import base64
import io
import json
import socket
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
HUB = HERE.parent
sys.path.insert(0, str(HUB / "tools" / "tag_reference"))
sys.path.insert(0, str(HUB / "tools" / "stego_research" / "sims"))

import embed  # noqa: E402
import tag_block  # noqa: E402
from PIL import Image  # noqa: E402
import numpy as np  # noqa: E402


def free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


def post(port, path, obj):
    """POST and return (status_code, body).  A 403 is a valid answer here, not an error."""
    req = urllib.request.Request(
        f"http://127.0.0.1:{port}{path}",
        data=json.dumps(obj).encode(),
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return r.status, json.loads(r.read())
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"{}")


def b64_of(arr):
    buf = io.BytesIO()
    Image.fromarray(arr.astype("uint8")).save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode()


def main():
    port = free_port()
    proc = subprocess.Popen(
        [sys.executable, str(HERE / "gateway.py"), "--port", str(port)],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    time.sleep(2)
    failures = []
    try:
        # --- build a marked image -------------------------------------
        cover, roi = embed.make_cover(7010)
        blk = tag_block.build_block(embed.HUB_KEY, tag_block.CURRENT_VERSION,
                                    embed.DEMO_HUB_ID, tag_block.new_handle(7010))
        marked, info = embed.mark(cover, roi, blk)
        print(f"marked image: capacity {info['blocks_available_per_region']}")

        # --- status ---------------------------------------------------
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/status", timeout=10) as r:
            st = json.loads(r.read())
        print(f"GET  /status -> {st}")
        if not st.get("ok"):
            failures.append("status not ok")

        # --- submit (lab tech) ----------------------------------------
        code, res = post(port, "/api/v1/submit",
                          {"title": "E2E test", "body": "generated by e2e_test.py",
                           "image_b64": b64_of(marked)})
        print(f"POST /api/v1/submit -> {res}")
        handle = res.get("handle")
        if not handle:
            failures.append("submit returned no handle")

        # --- verify the marked image (gateway extracts the tag) -------
        code, res = post(port, "/api/v1/verify", {"image_b64": b64_of(marked)})
        print(f"POST /api/v1/verify (marked) -> {res}")
        if not res.get("ok"):
            failures.append("verify of a marked image failed")

        # --- verify an unmarked image: must NOT verify -----------------
        unmarked = cover.copy()
        code, res2 = post(port, "/api/v1/verify", {"image_b64": b64_of(unmarked)})
        print(f"POST /api/v1/verify (unmarked) -> {res2}")
        if res2.get("ok"):
            failures.append("FALSE ACCEPT: an unmarked image verified")

        # --- records ---------------------------------------------------
        code, res3 = post(port, "/api/v1/records", {"handle": handle})
        print(f"POST /api/v1/records -> {res3}")
        if "record_view" not in res3:
            failures.append("records returned no record_view")

        # --- records for an unknown handle: must be denied -------------
        code, res4 = post(port, "/api/v1/records", {"handle": "H-does-not-exist"})
        print(f"POST /api/v1/records (unknown) -> {res4}")
        if "record_view" in res4:
            failures.append("records returned a record for an unknown handle")
    finally:
        proc.terminate()
        proc.wait(timeout=10)

    print()
    if failures:
        for f in failures:
            print(f"FAIL: {f}")
        sys.exit(1)
    print("PASS: gateway e2e -- submit, verify (marked), reject (unmarked), records")


if __name__ == "__main__":
    main()
