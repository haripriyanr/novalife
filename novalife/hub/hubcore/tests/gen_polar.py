#!/usr/bin/env python3
"""Golden data for polar: also (re)writes src/polar_tables.h from the Python reference."""
import sys, struct
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "tools" / "stego_research" / "sims"))
import polar_codec as pc

# ---- table header
idx = [int(v) for v in pc.RELIABLE_INDICES]
assert len(idx) == 128 and len(set(idx)) == 128
with open(HERE.parent / "src" / "polar_tables.h", "w") as f:
    f.write("/* GENERATED by tests/gen_polar.py from polar_codec.RELIABLE_INDICES; do not edit. */\n")
    f.write("const uint16_t hc_polar_info_index[128] = {\n")
    for i in range(0, 128, 16):
        f.write("    " + ", ".join(str(v) for v in idx[i:i+16]) + ",\n")
    f.write("};\n")

rng = np.random.default_rng(20261022)
G = HERE / "golden"
G.mkdir(exist_ok=True)

# ---- encode: 500 random inputs, text lines "info256hex... " as bit strings
with open(G / "polar_encode.txt", "w") as f:
    cases = [np.zeros(128, np.uint8), np.ones(128, np.uint8)]
    for i in range(128):
        e = np.zeros(128, np.uint8); e[i] = 1; cases.append(e)
    while len(cases) < 500:
        cases.append(rng.integers(0, 2, 128).astype(np.uint8))
    for c in cases:
        x = pc.polar_encode(c)
        f.write("".join(map(str, c)) + " " + "".join(map(str, x)) + "\n")

# ---- decode: binary records: 256 float64 llr, 128 info bytes, float64 pm
# classes: clean noiseless (+-big), several SNR, hard (near/under capacity) cases
def mk(snr_db_ebn0, n_cases, scale_extra=1.0):
    out = []
    rate = 0.5
    sigma = np.sqrt(1.0 / (2 * rate * 10 ** (snr_db_ebn0 / 10)))
    for _ in range(n_cases):
        info = rng.integers(0, 2, 128).astype(np.uint8)
        x = pc.polar_encode(info)
        tx = 1.0 - 2.0 * x
        y = tx + sigma * rng.standard_normal(256)
        llr = 2 * y / sigma**2 * scale_extra
        out.append((llr, info))
    return out
cases = []
cases += mk(30.0, 20)
for snr in (6.0, 4.0, 3.0, 2.5, 2.0, 1.5, 1.0, 0.5, 0.0):
    cases += mk(snr, 40)
# quantised-ish / integer LLRs (create ties!) and zero LLR erasures
for _ in range(60):
    info = rng.integers(0, 2, 128).astype(np.uint8)
    x = pc.polar_encode(info)
    llr = (1 - 2.0 * x) * rng.integers(1, 8, 256) + rng.integers(-4, 5, 256)
    llr = llr.astype(np.float64)
    llr[rng.random(256) < 0.3] = 0.0
    cases.append((llr, info))
# hard: heavy erasures with all LLR magnitudes equal (tie stress)
for _ in range(30):
    info = rng.integers(0, 2, 128).astype(np.uint8)
    x = pc.polar_encode(info)
    llr = (1 - 2.0 * x) * 1.0
    flip = rng.random(256) < 0.12
    llr[flip] *= -1
    llr[rng.random(256) < 0.2] = 0.0
    cases.append((llr.astype(np.float64), info))
print("decode cases:", len(cases))
ndiff = 0
with open(G / "polar_decode.bin", "wb") as f:
    f.write(struct.pack("<I", len(cases)))
    for llr, info in cases:
        dec, pm = pc.polar_scl_decode(llr)
        ndiff += int(np.any(dec != info))
        f.write(llr.astype("<f8").tobytes())
        f.write(dec.astype(np.uint8).tobytes())
        f.write(struct.pack("<d", pm))
print("python decodes != transmitted info in", ndiff, "cases (expected for hard SNR)")
