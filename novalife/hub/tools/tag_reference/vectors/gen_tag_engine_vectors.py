"""Emit conformance vectors for the PL tag engine (BUILD_TAG / VERIFY_TAG).

Contract: `tag_block.compute_tag(key, version, hub_id, handle)` -- the 48-bit truncated Ascon
MAC the Python reference embeds.  The engine must build exactly this tag and accept a block
only when its 48 bits equal it.

What the MAC actually authenticates (measured here, asserted below, and what the RTL
streams as associated data, 54 bytes):

    MAC_DOMAIN || MAC_DOMAIN || len(header)=0x0B || version(1) || hub_id(2, BE) || handle(8, BE)

`MAC_DOMAIN` appears twice because `compute_tag` prepends it and `mac_truncated` prepends it
again.  Harmless (fixed, public bytes), but it is the contract, so the RTL does the same.
The header is 11 bytes (the `header_bytes_of` docstring says 10).

Writes te_key.mem (128-bit), te_fields.mem (version4|hub_id12|handle64 = 80-bit),
te_tag.mem (48-bit), te_params.vh, tag_engine_vectors.json.

Run:  novalife_hub/.venv/bin/python tools/tag_reference/vectors/gen_tag_engine_vectors.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import ascon_primitives as ap  # noqa: E402
import tag_block as tb  # noqa: E402

SEED = 20261020
M = 16


def ad_bytes(version: int, hub_id: int, handle: int) -> bytes:
    header = tb.header_bytes_of(version, hub_id, handle)
    return ap.MAC_DOMAIN + ap.MAC_DOMAIN + bytes([len(header)]) + header


def main() -> int:
    rng = np.random.default_rng(SEED)
    cases = []
    fixed = [
        (tb.DEMO_HUB_KEY, 1, 0x9A3, 0x0123456789ABCDEF),
        (bytes(16), 0, 0, 0),
        (bytes([0xFF] * 16), 15, 0xFFF, (1 << 64) - 1),
    ]
    for key, v, h, hd in fixed:
        cases.append((key, v, h, hd))
    while len(cases) < M:
        key = bytes(int(x) for x in rng.integers(0, 256, 16))
        cases.append((key, int(rng.integers(0, 16)), int(rng.integers(0, 4096)),
                      int(rng.integers(0, 2**63)) * 2 + int(rng.integers(0, 2))))

    out = []
    for key, v, h, hd in cases:
        tag = tb.compute_tag(key, v, h, hd)
        # the AD the RTL streams must give the same tag through the AEAD directly
        direct = ap.ascon_aead_encrypt(key, ap.NONCE_MAC, b"", ad_bytes(v, h, hd))[-16:][:6]
        assert int.from_bytes(direct, "big") == tag, "AD layout does not match compute_tag"
        assert len(ad_bytes(v, h, hd)) == 54
        out.append(tag)

    # the stored nonce and domain, so the RTL constants can be checked against the reference
    (HERE / "te_key.mem").write_text("".join(f"{c[0].hex()}\n" for c in cases))
    (HERE / "te_fields.mem").write_text(
        "".join(f"{(c[1] << 76) | (c[2] << 64) | c[3]:020x}\n" for c in cases))
    (HERE / "te_tag.mem").write_text("".join(f"{t:012x}\n" for t in out))
    (HERE / "te_params.vh").write_text("\n".join([
        "// GENERATED by tools/tag_reference/vectors/gen_tag_engine_vectors.py -- do not edit.",
        "`ifndef TE_PARAMS_VH",
        "`define TE_PARAMS_VH",
        f"localparam integer TE_NUM_VECTORS = {M};",
        f"localparam [127:0] TE_NONCE_MAC = 128'h{ap.NONCE_MAC.hex()};",
        f"localparam [167:0] TE_MAC_DOMAIN = 168'h{ap.MAC_DOMAIN.hex()};",
        "`endif // TE_PARAMS_VH", ""]))
    (HERE / "tag_engine_vectors.json").write_text(json.dumps({
        "generator": "tools/tag_reference/vectors/gen_tag_engine_vectors.py",
        "date": "2026-10-20",
        "reference": "tools/tag_reference/tag_block.compute_tag",
        "ad_layout": "MAC_DOMAIN||MAC_DOMAIN||0x0B||version(1)||hub_id(2,BE)||handle(8,BE), 54 bytes",
        "nonce": ap.NONCE_MAC.hex(),
        "vectors": [{"key": c[0].hex(), "version": c[1], "hub_id": c[2],
                     "handle": f"{c[3]:016x}", "tag48": f"{t:012x}"}
                    for c, t in zip(cases, out)],
    }, indent=2) + "\n")
    print(f"self-check: streamed 54-byte AD == compute_tag on {M} cases  [PASS]")
    print(f"wrote {M} tag-engine vectors to {HERE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
