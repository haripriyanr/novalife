"""Emit G2 conformance vectors for the polar codec (N=256, K=128).

This script is the **single source of truth** for the polar stage's bit layout. It:

  1. self-checks the reference fast transform against the textbook Kronecker-product
     definition (F = [[1,0],[1,1]], codeword = u * F^(tensor 8) over GF(2)), so a wrong
     reference cannot silently become the standard;
  2. writes `polar_params.vh`, the Verilog constants the RTL needs (frozen mask and the
     info-bit position map) — generated, never hand-edited;
  3. writes `polar_enc_info.mem` / `polar_enc_code.mem`, M deterministic (info, codeword)
     pairs for `$readmemh` in the testbench;
  4. writes `polar_encode_vectors.json` with the same cases plus provenance, for humans
     and for other-language re-implementations.

Bit-order contract (fixed here, used by the RTL and the testbench):

  * bit `j` of a vector is `x[j]`;
  * the integer value of a bit vector is `sum(x[j] << j)` (bit 0 is the LSB);
  * a `.mem` line is that integer in hex, `$readmemh`-compatible.

Run:  novalife_hub/.venv/bin/python tools/tag_reference/vectors/gen_polar_vectors.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
SIMS = HERE.parents[1] / "stego_research" / "sims"
sys.path.insert(0, str(SIMS))

import polar_codec  # noqa: E402  (path set above)

N = polar_codec.N
K = polar_codec.K
M = 64  # number of encode vectors
SEED = 20261019


# --- independent reference: the textbook Kronecker construction -----------------


def kron_transform(u: np.ndarray) -> np.ndarray:
    """x = u * F^(tensor m) over GF(2), computed the slow, definitional way."""
    m = int(np.log2(len(u)))
    # F^(tensor m): 2x2 base, doubled m times
    F = np.array([[1, 0], [1, 1]], dtype=np.uint8)
    Fm = F.copy()
    for _ in range(m - 1):
        Fm = np.kron(Fm, F) % 2
    # codeword = Fm^T @ u  (row-vector convention: x = u @ Fm  ==  Fm^T @ u)
    return (Fm.T @ np.asarray(u, dtype=np.uint8)) % 2


def bits_to_int(bits: np.ndarray) -> int:
    """bit j is x[j]; int = sum(bits[j] << j)."""
    v = 0
    for j, b in enumerate(bits):
        if int(b):
            v |= (1 << j)
    return v


def main() -> int:
    rng = np.random.default_rng(SEED)

    # 1. self-check the fast transform against the definitional one
    for t in range(16):
        u = rng.integers(0, 2, N, dtype=np.uint8)
        fast = polar_codec.polar_transform(u)
        slow = kron_transform(u)
        if not np.array_equal(fast, slow):
            bad = int(np.argmax(fast != slow))
            raise SystemExit(
                f"REFERENCE MISMATCH: fast transform != Kronecker at bit {bad}\n"
                f"  fast={int(fast[bad])} slow={int(slow[bad])}"
            )
    print("self-check: fast polar_transform == Kronecker F^(tensor 8)  [16 random u, PASS]")

    frozen = polar_codec.FROZEN_MASK
    # ORDER MATTERS: the reference does `u[RELIABLE_INDICES] = info_bits`, so info bit j
    # goes to channel RELIABLE_INDICES[j].  Do not sort this.
    reliable = np.asarray(polar_codec.RELIABLE_INDICES, dtype=int)
    assert reliable.size == K, reliable.size
    assert np.unique(reliable).size == K, "reliable indices are not unique"
    assert not np.any(frozen[reliable]), "a reliable index is frozen"
    assert int(frozen.sum()) == N - K, int(frozen.sum())

    # info-bit position map: for each channel index i, which info bit (0..K-1) it carries,
    # or 0xFF if frozen.  This reproduces `u[RELIABLE_INDICES] = info_bits` exactly.
    info_pos = np.full(N, 0xFF, dtype=np.uint8)
    for j, i in enumerate(reliable):
        info_pos[i] = j

    # 2. vectors
    infos = rng.integers(0, 2, size=(M, K), dtype=np.uint8)
    codes = np.array([polar_codec.polar_encode(infos[t]) for t in range(M)], dtype=np.uint8)
    # sanity: encoding is linear and frozen positions of u are zero
    for t in range(M):
        u = np.zeros(N, dtype=np.uint8)
        u[reliable] = infos[t]
        assert np.array_equal(polar_codec.polar_transform(u), codes[t])

    (HERE / "polar_enc_info.mem").write_text(
        "".join(f"{bits_to_int(infos[t]):032x}\n" for t in range(M))
    )
    (HERE / "polar_enc_code.mem").write_text(
        "".join(f"{bits_to_int(codes[t]):064x}\n" for t in range(M))
    )

    # 3. Verilog parameters
    mask_int = bits_to_int(frozen.astype(np.uint8))
    lines = [
        "// GENERATED by tools/tag_reference/vectors/gen_polar_vectors.py — do not edit by hand.",
        f"// polar N={N} K={K}; bit j of a vector is x[j]; int = sum(x[j] << j).",
        "//",
        "// POLAR_FROZEN_MASK : bit i = 1 when channel index i is frozen (carries 0).",
        "// polar_info_pos(i)  : info-bit index 0..K-1 carried by channel i, or 8'hFF if frozen.",
        "",
        "`ifndef POLAR_PARAMS_VH",
        "`define POLAR_PARAMS_VH",
        "",
        f"localparam integer POLAR_N = {N};",
        f"localparam integer POLAR_K = {K};",
        f"localparam integer POLAR_NUM_VECTORS = {M};",
        # widths are literal so the header can be included outside a module (no N in scope)
        f"localparam [255:0] POLAR_FROZEN_MASK = 256'h{mask_int:064x};",
        "",
        "function [7:0] polar_info_pos;",
        "    input [7:0] i;",
        "    begin",
        "        case (i)",
    ]
    for i in reliable:
        lines.append(f"            8'd{int(i)}: polar_info_pos = 8'd{int(info_pos[i])};")
    lines += [
        "            default: polar_info_pos = 8'hFF;",
        "        endcase",
        "    end",
        "endfunction",
        "",
        "// polar_channel_of_info(j) : channel index that carries info bit j (inverse map).",
        "function [7:0] polar_channel_of_info;",
        "    input [7:0] j;",
        "    begin",
        "        case (j)",
    ]
    for j, i in enumerate(reliable):
        lines.append(f"            8'd{int(j)}: polar_channel_of_info = 8'd{int(i)};")
    lines += [
        "            default: polar_channel_of_info = 8'hFF;",
        "        endcase",
        "    end",
        "endfunction",
        "",
        "`endif // POLAR_PARAMS_VH",
        "",
    ]
    (HERE / "polar_params.vh").write_text("\n".join(lines))

    # 4. JSON
    (HERE / "polar_encode_vectors.json").write_text(
        json.dumps(
            {
                "generator": "tools/tag_reference/vectors/gen_polar_vectors.py",
                "date": "2026-10-19",
                "reference": "tools/stego_research/sims/polar_codec.py",
                "params": {"N": N, "K": K, "num_vectors": M, "seed": SEED},
                "bit_order": "bit j is x[j]; int = sum(x[j] << j)",
                "selftest": "fast polar_transform == Kronecker F^(tensor 8) on 16 random u",
                "frozen_mask_hex": f"{mask_int:064x}",
                "reliable_indices": [int(i) for i in reliable],
                "vectors": [
                    {
                        "i": t,
                        "info_hex": f"{bits_to_int(infos[t]):032x}",
                        "codeword_hex": f"{bits_to_int(codes[t]):064x}",
                    }
                    for t in range(M)
                ],
            },
            indent=2,
        )
        + "\n"
    )

    print(f"wrote {M} encode vectors + polar_params.vh to {HERE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
